#!/usr/bin/env bash
# Scan work/extracted (read-only) for secrets and risky patterns.
# Writes catalog/scan-findings.md and work/gitleaks.json.
set -uo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
ex="$root/work/extracted"
out="$root/catalog/scan-findings.md"

# Skip media/binaries and vendored deps.
GREP=(grep -rnIE --exclude-dir=node_modules --exclude-dir=.git --exclude=*.lock --exclude=package-lock.json
      --exclude=*.min.js --exclude=*.map --exclude=*.svg)

section() { # title, regex
  local title="$1" re="$2"
  echo "## $title"
  echo
  echo '```'
  ( cd "$ex" && "${GREP[@]}" "$re" . 2>/dev/null | cut -c1-220 | sort | head -400 )
  echo '```'
  echo
}

gitleaks dir "$ex" --no-banner --redact --report-format json --report-path "$root/work/gitleaks.json" >/dev/null 2>&1
leaks=$(python3 -I -c 'import json,sys; d=json.load(open(sys.argv[1])); print(len(d)); [print("-", x["File"].split("work/extracted/")[-1]+":"+str(x["StartLine"]), x["RuleID"]) for x in d]' "$root/work/gitleaks.json")

{
  echo "# Scan findings"
  echo
  echo "Generated by \`tools/scan.sh\` over \`work/extracted/\`. Paths are relative to it; the first path segment is the item ID. A hit is a lead for the Phase 2 review, not a verdict."
  echo
  echo "## gitleaks (redacted)"
  echo
  echo "Count: $leaks" | head -1
  echo "$leaks" | tail -n +2
  echo
  section "curl/wget piped to a shell" '(curl|wget)[^|#]*\|[[:space:]]*(sudo[[:space:]]+)?(ba|z)?sh\b'
  section "Permission bypass / skip-permissions" 'bypassPermissions|dangerously-skip-permissions|--yolo|dangerouslyDisableSandbox'
  section "Wildcard permission allows" '"(Bash|Write|Edit|Read)\((\*|\*\*|rm:\*|chmod[^)]*|sudo[^)]*)\)"|"Bash"[[:space:]]*[,\]]'
  section "Writers of global agent config" '(~|\$HOME|homedir\(\)|expanduser)[^"'"'"' ]*/\.(claude|codex|gemini|hermes|agents|openclaw)\b[^ ]*(settings|config|hooks|AGENTS|CLAUDE)'
  section "Outbound URLs in hooks/scripts (non-github docs)" 'https?://(api\.|gateway|ai-gateway|.*\.workers\.dev|.*webhook|hooks\.)[^ "'"'"')]*'
  section "Telemetry" '(telemetry|posthog|segment\.io|mixpanel|amplitude)[^a-z]'
  section "Destructive commands" 'rm[[:space:]]+-rf[[:space:]]+(/|~|\$HOME)|git[[:space:]]+push[[:space:]]+(-f|--force)|git[[:space:]]+reset[[:space:]]+--hard'
} > "$out"
echo "wrote $out"
